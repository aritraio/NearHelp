"""Generate complete Android resource sets from the reviewed UTF-8 translation catalog."""
from pathlib import Path
import csv
import re
from xml.sax.saxutils import escape

root = Path(__file__).resolve().parents[1]
rows = list(csv.reader((root / 'localization/ui-translations.tsv').open(encoding='utf-8'), delimiter='\t'))
assert all(len(row) == 3 for row in rows)
assert len({row[0] for row in rows}) == len(rows), 'Duplicate English UI text'
keys = []
for index, row in enumerate(rows):
    slug = re.sub('[^a-z0-9]+', '_', row[0].lower()).strip('_')[:65]
    key = 'ui_' + slug
    if key in keys:
        key += '_' + str(index)
    keys.append(key)

def android_text(value):
    return escape(value).replace("'", "\\'").replace('"', '\\"')

for column, folder in enumerate(('values', 'values-bn', 'values-hi')):
    dest = root / 'app/src/main/res' / folder
    dest.mkdir(parents=True, exist_ok=True)
    lines = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- Generated by tools/generate_ui_strings.py; edit localization/ui-translations.tsv. -->', '<resources>']
    for key, row in zip(keys, rows):
        assert sorted(re.findall(r'%\d+\$s', row[0])) == sorted(re.findall(r'%\d+\$s', row[column])), row[0]
        lines.append(f'    <string name="{key}">{android_text(row[column])}</string>')
    if column == 0:
        lines += ['    <array name="ui_text_resources">'] + [f'        <item>@string/{key}</item>' for key in keys] + ['    </array>']
    lines.append('</resources>')
    (dest / 'ui_strings.xml').write_text('\n'.join(lines) + '\n', encoding='utf-8')
print(f'Generated {len(rows)} interface strings in English, Bengali and Hindi.')
